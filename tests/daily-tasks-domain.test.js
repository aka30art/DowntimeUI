import assert from "node:assert/strict";
import {completedTaskCount,createDailyTaskState,saveAndLockDailyTasks,setTaskCompletion,validateTaskTemplates,visibleDailyTasks} from "../src/domain/daily-tasks.js";
const templates=[{id:"t1",name:"Safety inspection"},{id:"t2",name:"Check equipment"}];
assert.deepEqual(validateTaskTemplates(templates),[]);
assert.ok(validateTaskTemplates([{id:"x",name:"One"},{id:"x",name:"Two"}]).some(x=>x.includes("IDs must be unique")));
assert.ok(validateTaskTemplates([{id:"x",name:"Same"},{id:"y",name:"same"}]).some(x=>x.includes("names must be unique")));
let day=createDailyTaskState();
assert.equal(visibleDailyTasks(day,templates).length,2);
let toggle=setTaskCompletion(day,"t1",true,templates);
assert.equal(toggle.ok,true);day=toggle.state;
assert.equal(completedTaskCount({...day,snapshot:templates}),1);
const locked=saveAndLockDailyTasks(day,templates,{actorId:"operator-1",now:new Date("2026-11-22T05:00:00.000Z")});
assert.equal(locked.ok,true);
assert.equal(locked.state.lockedAt,"2026-11-22T05:00:00.000Z");
assert.equal(locked.state.lockedBy,"operator-1");
assert.deepEqual(locked.state.snapshot,templates);
assert.deepEqual(locked.state.completedTaskIds,["t1"]);
const reject=setTaskCompletion(locked.state,"t2",true,templates);
assert.equal(reject.ok,false);assert.equal(reject.code,"DAY_LOCKED");
assert.deepEqual(reject.state,locked.state);
const repeat=saveAndLockDailyTasks(locked.state,[{id:"t3",name:"Different later template"}]);
assert.equal(repeat.ok,true);assert.equal(repeat.alreadyLocked,true);
assert.deepEqual(repeat.state.snapshot,templates,"a locked day's snapshot must not drift when presets later change");
const empty=saveAndLockDailyTasks(createDailyTaskState(),[]);
assert.equal(empty.ok,false);
assert.ok(empty.errors[0].includes("at least one"));
const missing=setTaskCompletion(createDailyTaskState(),"missing",true,templates);
assert.equal(missing.code,"TASK_NOT_FOUND");
console.log("Daily task checklist, immutable snapshots and SAVE & LOCK behaviour: PASS");
