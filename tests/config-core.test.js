import assert from "node:assert/strict";
import { cloneDefaultConfig, validateConfig, createTenantConfig, activateInstall } from "../src/config-core.js";
const empty=cloneDefaultConfig();
assert.equal(empty.installed,false);
assert.equal(empty.identity.companyName,"");
assert.deepEqual(empty.site.areas,[]);
assert.deepEqual(empty.site.stations,[]);
assert.deepEqual(empty.downtime.reasons,[]);
assert.deepEqual(empty.schedule.workDays,[]);
assert.ok(validateConfig(empty).length>=2,"empty install should require identity and site");
const created=createTenantConfig({companyName:"Test Company",siteName:"Test Plant",timezone:"Europe/London"});
assert.equal(created.identity.companyName,"Test Company");
assert.equal(created.site.siteName,"Test Plant");
const result=activateInstall(created);
assert.equal(result.ok,true);
assert.equal(result.config.installed,true);
const invalid=activateInstall(cloneDefaultConfig());
assert.equal(invalid.ok,false);
assert.ok(invalid.errors.includes("Company name is required."));
assert.ok(invalid.errors.includes("Site or plant name is required."));
console.log("Universal configuration core: PASS");
