import assert from "node:assert/strict";
import {assignStationOperator,createPlantState,getPlantSummary,getStationOperationalState,normalizePlantState,setPlantStatus,setStationStatus} from "../src/domain/plant.js";
let state=createPlantState();
const stations=[{id:"s1",name:"Line 1"},{id:"s2",name:"Line 2"}],stationIds=stations.map(x=>x.id),staffIds=["p1","p2"];
assert.equal(state.status,"running");
let result=assignStationOperator(state,{stationId:"s1",staffId:"p1",stationIds,staffIds,stationName:"Line 1",staffName:"Operator One",at:"2026-11-22T06:30:00.000Z"});
assert.equal(result.ok,true);assert.equal(result.changed,true);state=result.state;
assert.equal(state.assignments.s1,"p1");
assert.equal(state.history[0].kind,"assignment");
assert.equal(assignStationOperator(state,{stationId:"s1",staffId:"p1",stationIds,staffIds}).changed,false);
assert.equal(assignStationOperator(state,{stationId:"s2",staffId:"p1",stationIds,staffIds}).code,"OPERATOR_ALREADY_ASSIGNED");
assert.equal(assignStationOperator(state,{stationId:"unknown",staffId:"p1",stationIds,staffIds}).code,"STATION_NOT_FOUND");
assert.equal(assignStationOperator(state,{stationId:"s1",staffId:"unknown",stationIds,staffIds}).code,"STAFF_NOT_FOUND");
result=setStationStatus(state,{stationId:"s2",status:"down",stationIds,stationName:"Line 2",at:"2026-11-22T07:00:00Z"});
assert.equal(result.ok,true);state=result.state;
assert.equal(getStationOperationalState(state,"s2"),"down");
assert.equal(setStationStatus(state,{stationId:"s2",status:"broken",stationIds}).code,"INVALID_STATION_STATUS");
result=setStationStatus(state,{stationId:"s2",status:"maintenance",stationIds});
assert.equal(result.ok,true);state=result.state;
assert.equal(getStationOperationalState(state,"s2"),"maintenance");
result=setPlantStatus(state,"stopped",{at:"2026-11-22T08:00:00Z"});
assert.equal(result.changed,true);state=result.state;
assert.equal(getStationOperationalState(state,"s1"),"suspended");
assert.equal(setPlantStatus(state,"stopped").changed,false);
result=setPlantStatus(state,"running",{at:"2026-11-22T09:00:00Z"});
assert.equal(result.changed,true);state=result.state;
assert.equal(getStationOperationalState(state,"s2"),"maintenance","station status should resume after plant restarts");
const summary=getPlantSummary(state,stations);
assert.equal(summary.status,"running");
assert.equal(summary.totalStations,2);
assert.equal(summary.runningStations,1);
assert.equal(summary.maintenanceStations,1);
assert.equal(summary.assignedStations,1);
assert.equal(summary.unassignedStations,1);
const legacy=normalizePlantState({status:"unknown",stationStates:{s1:"down"},assignments:{s1:"p1"},history:[]});
assert.equal(legacy.status,"running");
assert.equal(getStationOperationalState(legacy,"s1"),"down");
console.log("Plant and station states, exclusive assignments and local change history: PASS");
