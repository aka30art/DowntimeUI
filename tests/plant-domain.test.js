import assert from "node:assert/strict";
import {assignStationOperator,createPlantState,getPlantSummary,getStationOperationalState,setPlantStatus,setStationStatus} from "../src/domain/plant.js";
let state=createPlantState();
const stations=[{id:"s1"},{id:"s2"}],stationIds=stations.map(x=>x.id),staffIds=["p1","p2"];
assert.equal(state.plantOn,true);
let result=assignStationOperator(state,{stationId:"s1",staffId:"p1",stationIds,staffIds,at:"2026-11-22T06:30:00.000Z"});
assert.equal(result.ok,true);assert.equal(result.changed,true);state=result.state;
assert.equal(state.stationAssignments.s1,"p1");
assert.equal(assignStationOperator(state,{stationId:"s2",staffId:"p1",stationIds,staffIds}).code,"OPERATOR_ALREADY_ASSIGNED");
assert.equal(state.transitions[0].type,"station-assignment");
result=assignStationOperator(state,{stationId:"s1",staffId:"p1",stationIds,staffIds});
assert.equal(result.changed,false);
assert.equal(assignStationOperator(state,{stationId:"unknown",staffId:"p1",stationIds,staffIds}).code,"STATION_NOT_FOUND");
assert.equal(assignStationOperator(state,{stationId:"s1",staffId:"unknown",stationIds,staffIds}).code,"STAFF_NOT_FOUND");
result=setStationStatus(state,{stationId:"s2",active:false,stationIds,at:"2026-11-22T07:00:00Z"});
assert.equal(result.ok,true);state=result.state;
assert.equal(getStationOperationalState(state,"s2"),"stopped");
result=setPlantStatus(state,false,{at:"2026-11-22T08:00:00Z"});
assert.equal(result.changed,true);state=result.state;
assert.equal(getStationOperationalState(state,"s1"),"suspended");
assert.equal(getStationOperationalState(state,"s2"),"suspended");
result=setStationStatus(state,{stationId:"s2",active:true,stationIds});
assert.equal(result.ok,false);assert.equal(result.code,"PLANT_OFF");
result=setPlantStatus(state,true,{at:"2026-11-22T09:00:00Z"});
assert.equal(result.changed,true);state=result.state;
assert.equal(getStationOperationalState(state,"s2"),"stopped","previous station state should resume when plant is turned back on");
result=setStationStatus(state,{stationId:"s2",active:true,stationIds});
assert.equal(result.ok,true);state=result.state;
assert.equal(getStationOperationalState(state,"s2"),"running");
const summary=getPlantSummary(state,stations);
assert.equal(summary.plantOn,true);
assert.equal(summary.totalStations,2);
assert.equal(summary.runningStations,2);
assert.equal(summary.assignedStations,1);
assert.equal(summary.unassignedStations,1);
assert.equal(summary.transitions.length,4);
console.log("Plant status, station status, operator assignment and transition history: PASS");
